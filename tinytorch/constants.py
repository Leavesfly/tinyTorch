"""集中管理框架内部共享的数值常量。

本模块仅收拢 **跨模块复用** 的数值稳定性常量与安全阈值，
以避免同一语义常量在多处被独立硬编码、取值不一致或注释缺失。

约束:
    - 此处定义的常量都是框架内部实现细节，不属于对外公共 API。
    - 面向用户的 API 默认参数（例如 `Adam(epsilon=1e-8)`、`Log(epsilon=...)`）
      不应依赖此模块的值，保持各算法自身的语义独立性。
    - 新增常量前需确认至少有 2 处实际用到，否则应保留在使用处作为私有常量。
"""

# ---------------------------------------------------------------------------
# 数值稳定性
# ---------------------------------------------------------------------------

#: 反向传播中防止除零、log(0) 等情况的通用小常数。
#: 用于: autograd.ops.utils (梯度归约工具)、多种 Function 的 backward。
DEFAULT_EPSILON: float = 1e-10

# ---------------------------------------------------------------------------
# math.exp / sigmoid 的安全阈值
# ---------------------------------------------------------------------------
# Python 的 math.exp 在输入超过约 709.78 时溢过为 OverflowError，
# 在输入小于约 -745 时下溢为 0.0。对输入做预钳位可保证前向传播不中断，
# 并与主流框架（PyTorch/NumPy）在极端输入下的行为保持一致。

#: math.exp 的上溢阈值，超过此值将视为 +inf（或根据上下文返回 1.0）。
EXP_OVERFLOW_THRESHOLD: float = 709.0

#: math.exp 的下溢阈值，低于此值将视为 0.0。
EXP_UNDERFLOW_THRESHOLD: float = -745.0

# ---------------------------------------------------------------------------
# 随机数生成
# ---------------------------------------------------------------------------

#: Box-Muller 变换中 u1 的最小截断值，避免 math.log(0) 产生 -inf。
BOX_MULLER_MIN_U1: float = 1e-10


__all__ = [
    "DEFAULT_EPSILON",
    "EXP_OVERFLOW_THRESHOLD",
    "EXP_UNDERFLOW_THRESHOLD",
    "BOX_MULLER_MIN_U1",
]
